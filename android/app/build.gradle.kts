// Release signing comes from a file outside the repo (signing.properties
// next to this file, or SHEEPDOG_SIGNING pointing at one), never from git.
val signingFile = file(System.getenv("SHEEPDOG_SIGNING") ?: "signing.properties")
val signing = Properties().apply { if (signingFile.exists()) signingFile.inputStream().use { load(it) } }

android {
    namespace = "io.github.oysteinkrog.sheepdog"
    compileSdk = 36

    defaultConfig {
        applicationId = "io.github.oysteinkrog.sheepdog"
        minSdk = 29
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"
    }

    signingConfigs {
        if (signing.isNotEmpty()) {
            create("release") {
                storeFile = file(signing.getProperty("storeFile"))
                // The password comes from the environment (with-secrets), never from a file in git.
                val pw = System.getenv("SHEEPDOG_ANDROID_SIGNING_PASSWORD") ?: signing.getProperty("storePassword")
                storePassword = pw
                keyAlias = signing.getProperty("keyAlias")
                keyPassword = signing.getProperty("keyPassword") ?: pw
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            if (signing.isNotEmpty()) signingConfig = signingConfigs.getByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures { compose = true; buildConfig = true }
    testOptions { unitTests.isReturnDefaultValues = true }
}

